import { useState, useMemo } from 'react'
import { showToast } from './Toast.jsx'
import { computeReadability, computeKeywordDensity } from '../utils/api.js'
import './AnalysisResults.css'

function AnalysisResults({ analysis, resumeText, onStartInterview, onStartCoverLetter, onStartTools }) {
    const readability = useMemo(() => resumeText ? computeReadability(resumeText) : null, [resumeText])
    const keywords = useMemo(() => resumeText ? computeKeywordDensity(resumeText) : [], [resumeText])
    const [activeTab, setActiveTab] = useState('overview')

    if (!analysis) return null

    const copyToClipboard = (text, label = 'Text') => {
        navigator.clipboard.writeText(text)
        showToast(`${label} copied to clipboard!`, 'success')
    }

    const downloadEnhanced = () => {
        let content = '=== ENHANCED RESUME FEEDBACK ===\n'
        content += `Generated by ResumeAI Pro\n`
        content += `Date: ${new Date().toLocaleDateString()}\n\n`

        content += '--- OVERALL SCORE ---\n'
        content += `Score: ${analysis.overallScore}/100\n`
        content += `${analysis.scoreSummary}\n\n`

        if (analysis.atsScore) {
            content += '--- ATS COMPATIBILITY ---\n'
            content += `ATS Score: ${analysis.atsScore}/100\n`
            content += `${analysis.atsFeedback || ''}\n`
            if (analysis.atsKeywords?.found?.length) {
                content += `Keywords Found: ${analysis.atsKeywords.found.join(', ')}\n`
            }
            if (analysis.atsKeywords?.missing?.length) {
                content += `Keywords Missing: ${analysis.atsKeywords.missing.join(', ')}\n`
            }
            content += '\n'
        }

        if (analysis.strengths?.length) {
            content += '--- STRENGTHS ---\n'
            analysis.strengths.forEach((s, i) => { content += `${i + 1}. ${s}\n` })
            content += '\n'
        }

        if (analysis.weaknesses?.length) {
            content += '--- WEAKNESSES ---\n'
            analysis.weaknesses.forEach((w, i) => { content += `${i + 1}. ${w}\n` })
            content += '\n'
        }

        content += '--- IMPROVED BULLET POINTS ---\n'
            ; (analysis.improvedBullets || []).forEach((b, i) => {
                content += `\n${i + 1}. Original:  ${b.original}\n   Improved: ${b.improved}\n`
            })

        content += '\n--- MISSING SKILLS ---\n'
            ; (analysis.missingSkills || []).forEach((s, i) => {
                content += `${i + 1}. ${s.skill} [${s.priority || 'medium'}] — ${s.reason}\n`
            })

        content += '\n--- PROJECT RECOMMENDATIONS ---\n'
            ; (analysis.projectRecommendations || []).forEach((p, i) => {
                content += `${i + 1}. ${p.title} [${p.difficulty || ''}]: ${p.description}\n`
            })

        content += '\n--- LINKEDIN SUMMARY ---\n'
        content += (analysis.linkedinSummary || 'N/A') + '\n'

        const blob = new Blob([content], { type: 'text/plain' })
        const url = URL.createObjectURL(blob)
        const a = document.createElement('a')
        a.href = url
        a.download = 'resume_feedback.txt'
        a.click()
        URL.revokeObjectURL(url)
        showToast('Report downloaded!', 'success')
    }

    const downloadMarkdown = () => {
        let md = '# Resume Analysis Report\n\n'
        md += `> Generated by **ResumeAI Pro** on ${new Date().toLocaleDateString()}\n\n`
        md += `## Overall Score: ${analysis.overallScore}/100\n${analysis.scoreSummary}\n\n`

        if (analysis.atsScore) {
            md += `## ATS Compatibility: ${analysis.atsScore}/100\n${analysis.atsFeedback || ''}\n\n`
        }

        if (analysis.strengths?.length) {
            md += '## Strengths\n'
            analysis.strengths.forEach(s => { md += `- ✅ ${s}\n` })
            md += '\n'
        }

        if (analysis.weaknesses?.length) {
            md += '## Areas for Improvement\n'
            analysis.weaknesses.forEach(w => { md += `- ⚠️ ${w}\n` })
            md += '\n'
        }

        md += '## Improved Bullet Points\n'
            ; (analysis.improvedBullets || []).forEach((b, i) => {
                md += `### ${i + 1}.\n- **Before:** ${b.original}\n- **After:** ${b.improved}\n\n`
            })

        md += '## Missing Skills\n'
            ; (analysis.missingSkills || []).forEach(s => {
                md += `- **${s.skill}** (${s.priority || 'medium'}) — ${s.reason}\n`
            })

        md += '\n## LinkedIn Summary\n' + (analysis.linkedinSummary || 'N/A') + '\n'

        const blob = new Blob([md], { type: 'text/markdown' })
        const url = URL.createObjectURL(blob)
        const a = document.createElement('a')
        a.href = url
        a.download = 'resume_feedback.md'
        a.click()
        URL.revokeObjectURL(url)
        showToast('Markdown report downloaded!', 'success')
    }

    const scoreColor = (score) => {
        if (score >= 80) return 'var(--score-excellent)'
        if (score >= 60) return 'var(--score-good)'
        if (score >= 40) return 'var(--score-average)'
        return 'var(--score-poor)'
    }

    const sectionScoreColor = (score) => {
        if (score >= 8) return 'var(--score-excellent)'
        if (score >= 6) return 'var(--score-good)'
        if (score >= 4) return 'var(--score-average)'
        return 'var(--score-poor)'
    }

    const priorityClass = (p) => {
        if (p === 'high') return 'priority-high'
        if (p === 'low') return 'priority-low'
        return 'priority-medium'
    }

    const tabs = [
        { id: 'overview', label: '📊 Overview' },
        { id: 'ats', label: '🤖 ATS Score' },
        { id: 'bullets', label: '🎯 Bullets' },
        { id: 'skills', label: '🧩 Skills' },
        { id: 'sections', label: '📝 Sections' },
        { id: 'grammar', label: '✍️ Grammar' },
        { id: 'readability', label: '📖 Readability' },
        { id: 'keywords', label: '🔑 Keywords' },
        { id: 'linkedin', label: '💼 LinkedIn' },
    ]

    return (
        <div className="results-wrapper">
            <div className="results-container">
                {/* Header */}
                <div className="results-header animate-in">
                    <div className="results-header-text">
                        <h1 className="results-title">Analysis Complete</h1>
                        <p className="results-subtitle">Here's a detailed breakdown of your resume with actionable improvements</p>
                    </div>
                    <div className="results-header-actions">
                        <div className="download-dropdown">
                            <button className="btn-secondary" onClick={downloadEnhanced} id="download-btn">
                                ⬇ TXT Report
                            </button>
                            <button className="btn-secondary" onClick={downloadMarkdown} id="download-md-btn">
                                ⬇ Markdown
                            </button>
                        </div>
                        <button className="btn-secondary" onClick={onStartCoverLetter} id="cover-letter-btn">
                            ✉️ Cover Letter
                        </button>
                        <button className="btn-secondary" onClick={onStartTools} id="tools-btn">
                            🧰 Tools
                        </button>
                        <button className="btn-primary" onClick={onStartInterview} id="start-interview-btn">
                            🎤 Interview Prep
                        </button>
                    </div>
                </div>

                {/* Score cards row */}
                <div className="score-row animate-in stagger-1">
                    <div className="score-card glass" id="score-card">
                        <div className="score-ring-wrapper">
                            <svg className="score-ring" viewBox="0 0 120 120">
                                <circle cx="60" cy="60" r="52" fill="none" stroke="var(--border-glass)" strokeWidth="8" />
                                <circle
                                    cx="60" cy="60" r="52" fill="none"
                                    stroke={scoreColor(analysis.overallScore)} strokeWidth="8" strokeLinecap="round"
                                    strokeDasharray={`${(analysis.overallScore / 100) * 327} 327`}
                                    transform="rotate(-90 60 60)"
                                    style={{ transition: 'stroke-dasharray 1.2s var(--ease-out)' }}
                                />
                            </svg>
                            <div className="score-value" style={{ color: scoreColor(analysis.overallScore) }}>
                                {analysis.overallScore}
                            </div>
                        </div>
                        <div className="score-info">
                            <h3 className="score-label">Overall Score</h3>
                            <p className="score-summary">{analysis.scoreSummary}</p>
                        </div>
                    </div>

                    {analysis.atsScore !== undefined && (
                        <div className="score-card glass" id="ats-score-card">
                            <div className="score-ring-wrapper">
                                <svg className="score-ring" viewBox="0 0 120 120">
                                    <circle cx="60" cy="60" r="52" fill="none" stroke="var(--border-glass)" strokeWidth="8" />
                                    <circle
                                        cx="60" cy="60" r="52" fill="none"
                                        stroke={scoreColor(analysis.atsScore)} strokeWidth="8" strokeLinecap="round"
                                        strokeDasharray={`${(analysis.atsScore / 100) * 327} 327`}
                                        transform="rotate(-90 60 60)"
                                        style={{ transition: 'stroke-dasharray 1.2s var(--ease-out) 0.3s' }}
                                    />
                                </svg>
                                <div className="score-value" style={{ color: scoreColor(analysis.atsScore) }}>
                                    {analysis.atsScore}
                                </div>
                            </div>
                            <div className="score-info">
                                <h3 className="score-label">ATS Score</h3>
                                <p className="score-summary">{analysis.atsFeedback || 'ATS compatibility rating'}</p>
                            </div>
                        </div>
                    )}
                </div>

                {/* Strengths / Weaknesses row */}
                {(analysis.strengths?.length > 0 || analysis.weaknesses?.length > 0) && (
                    <div className="sw-row animate-in stagger-2">
                        {analysis.strengths?.length > 0 && (
                            <div className="sw-card sw-strengths glass">
                                <h3 className="sw-title">✅ Strengths</h3>
                                <ul className="sw-list">
                                    {analysis.strengths.map((s, i) => <li key={i}>{s}</li>)}
                                </ul>
                            </div>
                        )}
                        {analysis.weaknesses?.length > 0 && (
                            <div className="sw-card sw-weaknesses glass">
                                <h3 className="sw-title">⚠️ Areas to Improve</h3>
                                <ul className="sw-list">
                                    {analysis.weaknesses.map((w, i) => <li key={i}>{w}</li>)}
                                </ul>
                            </div>
                        )}
                    </div>
                )}

                {/* Tabs */}
                <div className="tabs-bar animate-in stagger-3" id="results-tabs">
                    {tabs.map(t => (
                        <button
                            key={t.id}
                            className={`tab-btn ${activeTab === t.id ? 'active' : ''}`}
                            onClick={() => setActiveTab(t.id)}
                            id={`tab-${t.id}`}
                        >
                            {t.label}
                        </button>
                    ))}
                </div>

                {/* Tab content */}
                <div className="tab-content animate-in stagger-4">
                    {activeTab === 'overview' && (
                        <div className="overview-content">
                            <div className="overview-grid">
                                <div className="stat-card glass">
                                    <span className="stat-number">{(analysis.improvedBullets || []).length}</span>
                                    <span className="stat-label">Bullet Improvements</span>
                                </div>
                                <div className="stat-card glass">
                                    <span className="stat-number">{(analysis.missingSkills || []).length}</span>
                                    <span className="stat-label">Missing Skills</span>
                                </div>
                                <div className="stat-card glass">
                                    <span className="stat-number">{(analysis.projectRecommendations || []).length}</span>
                                    <span className="stat-label">Project Ideas</span>
                                </div>
                                <div className="stat-card glass">
                                    <span className="stat-number">{(analysis.grammarIssues || []).length}</span>
                                    <span className="stat-label">Grammar Fixes</span>
                                </div>
                            </div>

                            {/* Section score bars */}
                            {analysis.sectionFeedback && (
                                <div className="section-bars glass">
                                    <h3 className="section-bars-title">Section Scores</h3>
                                    {Object.entries(analysis.sectionFeedback).map(([key, sec]) => (
                                        <div className="section-bar-row" key={key}>
                                            <span className="bar-label">{key.replace(/_/g, ' ')}</span>
                                            <div className="bar-track">
                                                <div
                                                    className="bar-fill"
                                                    style={{
                                                        width: `${(sec.score / 10) * 100}%`,
                                                        background: sectionScoreColor(sec.score),
                                                        transition: 'width 1s var(--ease-out)',
                                                    }}
                                                />
                                            </div>
                                            <span className="bar-value" style={{ color: sectionScoreColor(sec.score) }}>
                                                {sec.score}/10
                                            </span>
                                        </div>
                                    ))}
                                </div>
                            )}
                        </div>
                    )}

                    {activeTab === 'ats' && (
                        <div className="ats-content">
                            <div className="ats-keywords-row">
                                {analysis.atsKeywords?.found?.length > 0 && (
                                    <div className="ats-keyword-card glass">
                                        <h3 className="ats-kw-title success-text">✅ Keywords Found</h3>
                                        <div className="ats-kw-tags">
                                            {analysis.atsKeywords.found.map((kw, i) => (
                                                <span className="kw-tag kw-found" key={i}>{kw}</span>
                                            ))}
                                        </div>
                                    </div>
                                )}
                                {analysis.atsKeywords?.missing?.length > 0 && (
                                    <div className="ats-keyword-card glass">
                                        <h3 className="ats-kw-title danger-text">❌ Keywords Missing</h3>
                                        <div className="ats-kw-tags">
                                            {analysis.atsKeywords.missing.map((kw, i) => (
                                                <span className="kw-tag kw-missing" key={i}>{kw}</span>
                                            ))}
                                        </div>
                                    </div>
                                )}
                            </div>
                            <div className="ats-tips glass">
                                <h3>💡 ATS Tips</h3>
                                <ul className="ats-tips-list">
                                    <li>Use standard section headings (Education, Experience, Skills)</li>
                                    <li>Avoid images, tables, and complex formatting</li>
                                    <li>Include keywords from the job description naturally</li>
                                    <li>Use standard fonts and consistent formatting</li>
                                    <li>Spell out acronyms at least once</li>
                                </ul>
                            </div>
                        </div>
                    )}

                    {activeTab === 'bullets' && (
                        <div className="bullets-list">
                            {(analysis.improvedBullets || []).map((b, i) => (
                                <div className="bullet-card glass" key={i}>
                                    <div className="bullet-row">
                                        <span className="bullet-label danger-label">Before</span>
                                        <p className="bullet-text">{b.original}</p>
                                    </div>
                                    <div className="bullet-arrow">→</div>
                                    <div className="bullet-row">
                                        <span className="bullet-label success-label">After</span>
                                        <p className="bullet-text">{b.improved}</p>
                                    </div>
                                    <button
                                        className="copy-btn"
                                        onClick={() => copyToClipboard(b.improved, 'Improved bullet')}
                                        title="Copy improved bullet"
                                    >
                                        📋
                                    </button>
                                </div>
                            ))}
                        </div>
                    )}

                    {activeTab === 'skills' && (
                        <div className="skills-section">
                            <h3 className="section-title">Missing Skills for Your Target Role</h3>
                            <div className="skills-tags">
                                {(analysis.missingSkills || []).map((s, i) => (
                                    <div className="skill-tag glass" key={i}>
                                        <div className="skill-tag-header">
                                            <strong>{s.skill}</strong>
                                            {s.priority && (
                                                <span className={`priority-badge ${priorityClass(s.priority)}`}>
                                                    {s.priority}
                                                </span>
                                            )}
                                        </div>
                                        <span className="skill-reason">{s.reason}</span>
                                    </div>
                                ))}
                            </div>
                            <h3 className="section-title" style={{ marginTop: '32px' }}>Recommended Projects</h3>
                            <div className="projects-list">
                                {(analysis.projectRecommendations || []).map((p, i) => (
                                    <div className="project-card glass" key={i}>
                                        <div className="project-card-header">
                                            <h4 className="project-title">💡 {p.title}</h4>
                                            {p.difficulty && (
                                                <span className={`difficulty-badge diff-${p.difficulty}`}>{p.difficulty}</span>
                                            )}
                                        </div>
                                        <p className="project-desc">{p.description}</p>
                                    </div>
                                ))}
                            </div>
                        </div>
                    )}

                    {activeTab === 'sections' && (
                        <div className="section-feedback-list">
                            {Object.entries(analysis.sectionFeedback || {}).map(([key, sec]) => (
                                <div className="section-card glass" key={key}>
                                    <div className="section-card-header">
                                        <h4 className="section-name">{key.replace(/_/g, ' ')}</h4>
                                        <span className="section-score" style={{ color: sectionScoreColor(sec.score) }}>
                                            {sec.score}/10
                                        </span>
                                    </div>
                                    <p className="section-feedback-text">{sec.feedback}</p>
                                    <ul className="section-suggestions">
                                        {(sec.suggestions || []).map((s, i) => <li key={i}>{s}</li>)}
                                    </ul>
                                </div>
                            ))}
                        </div>
                    )}

                    {activeTab === 'grammar' && (
                        <div className="grammar-list">
                            {(analysis.grammarIssues || []).map((g, i) => (
                                <div className="grammar-card glass" key={i}>
                                    <div className="grammar-row">
                                        <span className="bullet-label danger-label">Issue</span>
                                        <p>{g.original}</p>
                                    </div>
                                    <div className="grammar-row">
                                        <span className="bullet-label success-label">Fix</span>
                                        <p>{g.corrected}</p>
                                    </div>
                                    <p className="grammar-explanation">💬 {g.explanation}</p>
                                    <button
                                        className="copy-btn"
                                        onClick={() => copyToClipboard(g.corrected, 'Corrected text')}
                                        title="Copy corrected text"
                                    >
                                        📋
                                    </button>
                                </div>
                            ))}
                        </div>
                    )}

                    {activeTab === 'readability' && readability && (
                        <div className="readability-section">
                            <div className="readability-score-card glass">
                                <div className="readability-ring-wrapper">
                                    <svg className="score-ring" viewBox="0 0 120 120">
                                        <circle cx="60" cy="60" r="52" fill="none" stroke="var(--border-glass)" strokeWidth="8" />
                                        <circle cx="60" cy="60" r="52" fill="none"
                                            stroke={readability.fleschScore >= 60 ? 'var(--success)' : readability.fleschScore >= 30 ? 'var(--warning)' : 'var(--danger)'}
                                            strokeWidth="8" strokeLinecap="round"
                                            strokeDasharray={`${(readability.fleschScore / 100) * 327} 327`}
                                            transform="rotate(-90 60 60)"
                                            style={{ transition: 'stroke-dasharray 1s var(--ease-out)' }} />
                                    </svg>
                                    <div className="score-value" style={{ color: readability.fleschScore >= 60 ? 'var(--success)' : readability.fleschScore >= 30 ? 'var(--warning)' : 'var(--danger)' }}>
                                        {readability.fleschScore}
                                    </div>
                                </div>
                                <div className="score-info">
                                    <h3 className="score-label">Flesch Readability</h3>
                                    <p className="score-summary">Grade Level: {readability.grade}</p>
                                </div>
                            </div>
                            <div className="readability-stats">
                                <div className="stat-card glass"><span className="stat-number">{readability.wordCount}</span><span className="stat-label">Words</span></div>
                                <div className="stat-card glass"><span className="stat-number">{readability.sentenceCount}</span><span className="stat-label">Sentences</span></div>
                                <div className="stat-card glass"><span className="stat-number">{readability.avgWordsPerSentence}</span><span className="stat-label">Avg Words/Sentence</span></div>
                            </div>
                            <div className="readability-tips glass">
                                <h3>💡 Readability Tips</h3>
                                <ul>
                                    <li>Aim for a Flesch score of 60+ for easy readability</li>
                                    <li>Keep sentences under 20 words on average</li>
                                    <li>Use simple, direct language — avoid jargon where possible</li>
                                    <li>Break long paragraphs into bullet points</li>
                                    <li>Recruiters spend ~7 seconds scanning a resume initially</li>
                                </ul>
                            </div>
                        </div>
                    )}

                    {activeTab === 'keywords' && (
                        <div className="keywords-section">
                            <h3 className="section-title">Top Keywords in Your Resume</h3>
                            <div className="keyword-bars glass">
                                {keywords.slice(0, 15).map((kw, i) => (
                                    <div className="keyword-bar-row" key={i}>
                                        <span className="keyword-word">{kw.word}</span>
                                        <div className="keyword-bar-track">
                                            <div className="keyword-bar-fill" style={{
                                                width: `${Math.min(100, (kw.count / (keywords[0]?.count || 1)) * 100)}%`,
                                                background: i < 5 ? 'var(--success)' : i < 10 ? 'var(--info)' : 'var(--text-muted)',
                                            }} />
                                        </div>
                                        <span className="keyword-count">{kw.count}x ({kw.percent}%)</span>
                                    </div>
                                ))}
                            </div>
                            <div className="readability-tips glass" style={{ marginTop: '16px' }}>
                                <h3>💡 Keyword Tips</h3>
                                <ul>
                                    <li>Include keywords from the target job description</li>
                                    <li>Use both acronyms and full forms (e.g., "ML" and "Machine Learning")</li>
                                    <li>Avoid keyword stuffing — use natural language</li>
                                    <li>Place important keywords in your summary and skills sections</li>
                                </ul>
                            </div>
                        </div>
                    )}

                    {activeTab === 'linkedin' && (
                        <div className="linkedin-section">
                            <div className="linkedin-card glass">
                                <div className="linkedin-header">
                                    <span className="linkedin-icon">💼</span>
                                    <h3>Generated LinkedIn Summary</h3>
                                </div>
                                <p className="linkedin-text">{analysis.linkedinSummary}</p>
                                <button
                                    className="btn-secondary"
                                    onClick={() => copyToClipboard(analysis.linkedinSummary, 'LinkedIn summary')}
                                    style={{ marginTop: '16px' }}
                                >
                                    📋 Copy to Clipboard
                                </button>
                            </div>
                        </div>
                    )}
                </div>
            </div>
        </div>
    )
}

export default AnalysisResults
